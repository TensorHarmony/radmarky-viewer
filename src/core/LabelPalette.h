[[nodiscard]] constexpr std::uint32_t defaultLabelColor(
    const std::uint16_t label) noexcept
{
    return label == 0
        ? 0U
        : defaultLabelColors[(static_cast<std::size_t>(label) - 1U)
                             % defaultLabelColors.size()];
}

